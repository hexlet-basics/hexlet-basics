// Command fixturelabels writes labels_gen.go: one fixtures.Label variable per
// label the rows in fixtures/ define (ADR-0001 style: the YAML is the source,
// the Go file is generated and never hand-edited).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
	"unicode"

	"hexletbasics/internal/fixtures"
)

func main() {
	dir := flag.String("dir", "fixtures", "directory of the fixture YAML files")
	out := flag.String("out", "labels_gen.go", "file to write")
	flag.Parse()

	names, err := fixtures.LabelNames(*dir)
	if err != nil {
		log.Fatal(err)
	}
	src, err := render(names)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o600); err != nil {
		log.Fatal(err)
	}
}

// render is the gofmt-ed source of labels_gen.go for the labels, which are
// already in name order. Two labels that spell the same identifier fail here
// instead of as a redeclaration in the generated file.
func render(names []string) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/fixturelabels; DO NOT EDIT.\n\npackage fixtures\n\nvar (\n")
	taken := map[string]string{}
	for _, name := range names {
		ident := identifier(name)
		if ident == "" {
			return nil, fmt.Errorf("fixture label %q has no letters or digits to name a variable after", name)
		}
		if other, dup := taken[ident]; dup {
			return nil, fmt.Errorf("fixture labels %q and %q both become %s; rename one", other, name, ident)
		}
		taken[ident] = name
		fmt.Fprintf(&buf, "\t%s = LabelOf(%q)\n", ident, name)
	}
	buf.WriteString(")\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return src, nil
}

// identifier is a label in the exported-name form: user_removed → UserRemoved.
func identifier(label string) string {
	var b strings.Builder
	for _, part := range strings.Split(label, "_") {
		if part == "" {
			continue
		}
		runes := []rune(part)
		runes[0] = unicode.ToUpper(runes[0])
		b.WriteString(string(runes))
	}
	return b.String()
}
